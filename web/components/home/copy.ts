export type Shot = { src: string; w: number; h: number; alt: string; cap?: string };
/** 원본의 % 영역만 크게 보이는 그림 — 핵심 자리를 확대할 때 쓴다(원본 파일은 그대로) */
export type Detail = Shot & { crop: [number, number, number, number] };
/** 작업마다 배치가 다르다: wide 큰 그림+옆 글 · phones 폰 화면 둘 · pair 전/후 비교 · full 꽉 찬 그림+확대 셋 */
export type WorkEntry = {
  layout: 'wide' | 'phones' | 'pair' | 'full';
  status?: string;
  /** 문제 → 설계 판단 → 바꾼 것. 판단은 사례 본문에 적힌 결정만 옮긴다 */
  problem: string; decision: string; changed: string;
  shots: Shot[];
  details?: Detail[];
  /** 두 화면 전환(사례 상세의 전환 단추와 같은 방식) — 실제 제품의 두 상태. 첫 화면은 shots[0] */
  toggle?: { names: [string, string]; next: Shot };
  /** pair 전용 — 전·후 비교 위에 짚는 자리(그림 %)와 그 자리의 변화. 나머지 비교는 상세 페이지에 있다 */
  marks?: { x: number; y: number; t: string }[];
};

